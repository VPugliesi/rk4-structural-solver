import numpy as np
import matplotlib.pyplot as plt

# 1. Physical and Seismic Parameters
m = 2.0e6       # mass [kg]
c = 2.0e5       # damping coefficient [N*s/m]
k = 1.5e8       # linear stiffness [N/m]
k3 = 1.0e10     # nonlinear stiffness [N/m^3]

Ap = 3.0        # primary wave amplitude [m/s^2]
An = 1.0        # normal wave amplitude [m/s^2]
wp = 4.0        # primary frequency [rad/s]
wn = 6.0        # normal frequency [rad/s]
phip = 0.0      # phase angles [rad]
phin = 0.0
theta = np.pi/6 # orientation angle [30 degrees]

# 2. Ground Motion Functions

def xi(t):      # Earthquake duration function (On/Off)
    return 1.0 if (0 <= t <= 10) else 0.0

def ag(t):     # Total combined ground acceleration
    return (Ap*np.sin(wp*t + phip) + An*np.sin(wn*t + phin)) * xi(t)

# Ground motion components based on theta
def agx(t): return ag(t) * np.cos(theta)
def agy(t): return ag(t) * np.sin(theta)

# 3. System of ODEs
# State-space representation of Duffing Oscillator
def deriv(t, Y):
    x, xdot, y, ydot = Y

    # Nonlinear equations of motion for x and y directions
    xddot = -(c/m)*xdot - (k/m)*x - (k3/m)*(x**3) - agx(t)
    yddot = -(c/m)*ydot - (k/m)*y - (k3/m)*(y**3) - agy(t)

    return np.array([xdot, xddot, ydot, yddot])

# 4. Numerical Solver (RK4)
# Fourth-Order Runge-Kutta
def solve_RK4(f, t0, Y0, h, Nt):
    t = t0 + h * np.arange(Nt + 1)
    Y = np.zeros((Nt + 1, len(Y0)))
    Y[0] = Y0
    for i in range(Nt):
        k1 = f(t[i], Y[i])
        k2 = f(t[i] + h/2, Y[i] + (h/2)*k1)
        k3 = f(t[i] + h/2, Y[i] + (h/2)*k2)
        k4 = f(t[i] + h, Y[i] + h*k3)
        Y[i+1] = Y[i] + (h/6)*(k1 + 2*k2 + 2*k3 + k4)
    return t, Y

# 5. Main Simulation
t0, tmax, h = 0.0, 30.0, 0.01
Nt = int(tmax / h)
Y_initial = np.array([0.0, 0.0, 0.0, 0.0]) # starting at rest
time, sol = solve_RK4(deriv, t0, Y_initial, h, Nt)

# Define Results
x, xdot = sol[:,0], sol[:,1]
y, ydot = sol[:,2], sol[:,3]

# Calculate accelerations and shear forces
xddot = -(c/m)*xdot - (k/m)*x - (k3/m)*(x**3)
yddot = -(c/m)*ydot - (k/m)*y - (k3/m)*(y**3)
Fx = k*x + k3*(x**3) + c*xdot # Base Shear Force x
Fy = k*y + k3*(y**3) + c*ydot # Base Shear Force y

# 6. Plotting Results

# Plot 1: Displacement TimeHistory
plt.figure(figsize=(10, 5))
plt.plot(time, x, label='x-direction', color='orange')
plt.plot(time, y, label='y-direction', color='green')
plt.xlabel('Time [s]')
plt.ylabel('Displacement [m]')
plt.grid(True)
plt.legend()

# Plot 2: Acceleration
plt.figure(figsize=(10, 5))
plt.plot(time, xddot, label='x-acceleration', color='orange')
plt.plot(time, yddot, label='y-acceleration', color='green')
plt.xlabel('Time [s]')
plt.ylabel('Acceleration [m/s^2]')
plt.grid(True)
plt.legend()

# Plot 3: Base Shear Force
plt.figure(figsize=(10, 5))
plt.plot(time, Fx, label='Shear Fx', color='orange')
plt.plot(time, Fy, label='Shear Fy', color='green')
plt.xlabel('Time [s]')
plt.ylabel('Shear Force [N]')
plt.grid(True)
plt.legend()

# Results Table
print(f"Peak Response Metrics")
print(f"Max x-Displacement: {np.max(np.abs(x)):.4f} m")
print(f"Max y-Displacement: {np.max(np.abs(y)):.4f} m")
print(f"Max x-Acceleration: {np.max(np.abs(xddot)):.4f} m/s^2")
print(f"Max Base Shear Fx:  {np.max(np.abs(Fx)):.2e} N")

plt.show()

# 7. Convergence Study
# Baseline time step
h_base = 0.01

# Generate ~60 test step sizes (fine resolution)
dt_values = np.linspace(0.002, 0.05, 60)
max_disp = []

for dt_test in dt_values:
    Nt_test = int(tmax / dt_test)
    t_test, sol_test = solve_RK4(deriv,t0,Y_initial,dt_test,Nt_test)
    x_test = sol_test[:, 0]
    max_disp.append(np.max(np.abs(x_test)))

# baseline result
baseline_index = np.argmin(np.abs(dt_values - h_base))
baseline_disp = max_disp[baseline_index]

# percent change in step size
percent_change_h = ((dt_values - h_base) / h_base) * 100

# percent change in result
percent_change_result = (
    (np.array(max_disp) - baseline_disp) / baseline_disp
) * 100

plt.figure(figsize=(8,6))
plt.plot(percent_change_h, percent_change_result, linewidth=2, color='blue')
plt.xlabel('Percent Change in Time Step (%)')
plt.ylabel('Percent Change in Maximum Displacement (%)')
plt.grid(True)
plt.show()

# 8. Sensitivity Analysis
def run_sim(c_in, k_in, k3_in, Ap_in, wp_in):
    def deriv_sweep(t, Y):
        x_s, xdot_s, y_s, ydot_s = Y
        ag_s = (Ap_in*np.sin(wp_in*t) + An*np.sin(wn*t)) * xi(t)
        ax_s = ag_s * np.cos(theta)
        xddot_s = -(c_in/m)*xdot_s - (k_in/m)*x_s - (k3_in/m)*(x_s**3) - ax_s
        return np.array([xdot_s, xddot_s, 0, 0])

    t, sol_s = solve_RK4(deriv_sweep, t0, Y_initial, 0.02, int(tmax/0.02))
    return np.max(np.abs(sol_s[:, 0]))

# Define baseline values
c0, k0, k30, Ap0, wp0 = c, k, k3, Ap, wp
p_factors = np.linspace(0.5, 1.5, 11) # +/- 50% variations

# 1. Define baseline result for normalization
baseline_res = run_sim(c0, k0, k30, Ap0, wp0)

x_c = [run_sim(c0*p, k0, k30, Ap0, wp0) for p in p_factors]
x_k = [run_sim(c0, k0*p, k30, Ap0, wp0) for p in p_factors]
x_k3 = [run_sim(c0, k0, k30*p, Ap0, wp0) for p in p_factors]
x_Ap = [run_sim(c0, k0, k30, Ap0*p, wp0) for p in p_factors]
x_wp = [run_sim(c0, k0, k30, Ap0, wp0*p) for p in p_factors]

# 2. Convert Parameter values to Percent Change (x-axis)
c_pct = (p_factors - 1) * 100
k_pct = (p_factors - 1) * 100
k3_pct = (p_factors - 1) * 100
Ap_pct = (p_factors - 1) * 100
wp_pct = (p_factors - 1) * 100

# 3. Convert Results to Percent Change (y-axis)
res_c_pct = ((np.array(x_c) - baseline_res) / baseline_res) * 100
res_k_pct = ((np.array(x_k) - baseline_res) / baseline_res) * 100
res_k3_pct = ((np.array(x_k3) - baseline_res) / baseline_res) * 100
res_Ap_pct = ((np.array(x_Ap) - baseline_res) / baseline_res) * 100
res_wp_pct = ((np.array(x_wp) - baseline_res) / baseline_res) * 100

plt.figure(figsize=(10,6))

# 4. Plotting the percentages
plt.plot(c_pct, res_c_pct, label="Damping c")
plt.plot(k_pct, res_k_pct, label="Stiffness k")
plt.plot(k3_pct, res_k3_pct, label="Nonlinear stiffness k3")
plt.plot(Ap_pct, res_Ap_pct, label="Earthquake amplitude Ap")
plt.plot(wp_pct, res_wp_pct, label="Frequency wp")

# Formatting
plt.xlabel("Percent Change in Parameter (%)")
plt.ylabel("Percent Change in Max Displacement (%)")
plt.axhline(0, color='black', linewidth=1) # Baseline reference line
plt.axvline(0, color='black', linewidth=1) # Baseline reference line
plt.legend()
plt.grid(True)

